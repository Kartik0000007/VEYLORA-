/**
 * Request validation helpers using express-validator.
 *
 * Provides standard validation chains and a middleware to
 * translate validation errors into consistent 400 responses.
 */

const { body, param, query, validationResult } = require('express-validator');

const handleValidationErrors = (req, res, next) => {
  const errors = validationResult(req);
  if (!errors.isEmpty()) {
    return res.status(400).json({
      error: 'Validation failed',
      details: errors.array().map((e) => ({
        field: e.path,
        message: e.msg,
        value: e.value,
      })),
    });
  }
  next();
};

module.exports = { body, param, query, validationResult, handleValidationErrors };
